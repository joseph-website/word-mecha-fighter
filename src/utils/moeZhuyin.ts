// 標點符號清單
const PUNCTUATION_REGEX = /[，。？！、；：「」『』—…（）《》〈〉""''.,!?:;()\-_\s]/;

/**
 * 依據台灣「教育部重編國語辭典修訂本」將文字轉成標準注音
 */
export function convertToMoeZhuyin(text: string): Array<{ char: string; zhuyin: string }> {
  const result: Array<{ char: string; zhuyin: string }> = [];
  let i = 0;

  // 取得所有詞組並按長度降冪排列 (最長匹配原則)
  const phrases = Object.keys(MOE_PHRASE_DICTIONARY).sort((a, b) => b.length - a.length);

  while (i < text.length) {
    const char = text[i];

    // 非中文字元或標點符號
    if (PUNCTUATION_REGEX.test(char) || /[a-zA-Z0-9]/.test(char)) {
      result.push({ char, zhuyin: '' });
      i++;
      continue;
    }

    // 嘗試比對詞組辭典
    let matchedPhrase = false;
    for (const phrase of phrases) {
      if (text.startsWith(phrase, i)) {
        const zhuyinList = MOE_PHRASE_DICTIONARY[phrase];
        for (let k = 0; k < phrase.length; k++) {
          const phraseChar = phrase[k];
          if (PUNCTUATION_REGEX.test(phraseChar)) {
            result.push({ char: phraseChar, zhuyin: '' });
          } else {
            result.push({ char: phraseChar, zhuyin: zhuyinList[k] || '' });
          }
        }
        i += phrase.length;
        matchedPhrase = true;
        break;
      }
    }

    if (matchedPhrase) continue;

    // 單字辭典優先比對
    if (MOE_CHAR_DICTIONARY[char]) {
      result.push({ char, zhuyin: MOE_CHAR_DICTIONARY[char] });
      i++;
      continue;
    }

    // 備援：透過 pinyin-pro 與 p2z 轉換並修正輕聲
    try {
      const pyList = pinyin(char, { toneType: 'num', type: 'all' }) as Array<{
        origin: string;
        pinyin: string;
        isZh: boolean;
      }>;
      const first = pyList[0];
      if (first && first.isZh) {
        let py = first.pinyin;
        let isNeutral = false;
        if (py.endsWith('0') || py.endsWith('5')) {
          py = py.replace(/[05]$/, '');
          isNeutral = true;
        }
        let zh = p2z(py);
        zh = zh.replace(/[0-9]/g, '');
        if (isNeutral && !zh.startsWith('˙')) {
          zh = '˙' + zh;
        }
        result.push({ char, zhuyin: zh });
      } else {
        result.push({ char, zhuyin: '' });
      }
    } catch {
      result.push({ char, zhuyin: '' });
    }

    i++;
  }

  return result;
}
